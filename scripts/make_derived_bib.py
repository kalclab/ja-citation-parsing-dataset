#!/usr/bin/env python3
"""Build the Phase 2 compile-only derived .bib from the source-faithful original.

    dataset/ja_bib_full.bib  --(this script)-->  dataset/ja_bib_derived.bib

The original is source-faithful (docs/phase1_conventions.md) and never modified.
The derived file mechanically fixes what would otherwise corrupt the generated
reference strings:

1. (--names-table) Enrichment from NDL authority records: replace enriched
   author/editor fields with their split form (姓, 名) and add a `yomi` field.
   Keyed by provisional_key, joined onto final keys via key_map.csv. Applied
   before step 2 so already-split names pass through untouched.
2. Japanese author names in "姓 名" (single space) -> "姓, 名". BibTeX otherwise
   parses the space form as given/family and (u)pBibTeX / citeproc reverse or
   drop the surname (see reports/style_survey.md). Romaji, institutional, and
   already-comma names are left untouched; genuinely ambiguous names (Japanese
   with >1 internal space) are left as-is and logged to stderr.
3. @misc URL duplication: keep the URL in `url` only and reduce `howpublished`
   to any non-URL remainder (else drop).

Usage:
    uv run python scripts/make_derived_bib.py \
        --in dataset/ja_bib_full.bib --out dataset/ja_bib_derived.bib \
        --names-table data/interim/enrich_names/name_boundaries.jsonl
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import biblib  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
NAME_FIELDS = ("author", "editor", "translator")
_URL_BRACE = re.compile(r"\\url\{([^}]*)\}")
_URL_RAW = re.compile(r"https?://\S+")

HEADER = (
    "% ja_bib_derived.bib — AUTO-GENERATED by scripts/make_derived_bib.py. DO NOT EDIT.\n"
    "% Phase 2 コンパイル専用の派生ファイル。原本 ja_bib_full.bib は編集しない。\n"
    "% 変換: 典拠 enrichment（著者分割・yomi）／日本語著者「姓 名」→「姓, 名」／@misc URL 一本化。\n"
    "% 再生成: uv run python scripts/make_derived_bib.py --names-table <table>\n\n"
)


def load_enrichment(table: Path, key_map: Path) -> dict[str, dict]:
    """{final_key: enrichment_record} by joining provisional_key via key_map."""
    prov2final: dict[str, str] = {}
    with key_map.open(encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            prov2final[row["provisional_key"]] = row["key"]
    out: dict[str, dict] = {}
    for line in table.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        rec = json.loads(line)
        fk = prov2final.get(rec["provisional_key"])
        if fk:
            out[fk] = rec
    return out


def apply_enrichment(entry: dict, enr: dict) -> tuple[list[str], list[str]]:
    """Apply split author/editor fields + yomi. Returns (changed, mismatched)."""
    by_field: dict[str, list[dict]] = {}
    for n in enr.get("names", []):
        by_field.setdefault(n["field"], []).append(n)
    changed: list[str] = []
    mismatched: list[str] = []
    for field in ("author", "editor"):
        fnames = by_field.get(field)
        if not fnames or not entry.get(field, "").strip():
            continue
        # sanity: reconstructed original must match the record (source may differ)
        orig = " and ".join(n["original"] for n in fnames)
        if biblib.norm_for_match(orig) != biblib.norm_for_match(entry[field]):
            mismatched.append(field)
            continue
        new = " and ".join((n.get("split") or n["original"]) for n in fnames)
        if new != entry[field]:
            entry[field] = new
            changed.append(field)
    # yomi is jecon/ipsjsort's AUTHOR sort key. NDL books ship a title-reading
    # `yomi`, which is wrong for that purpose, so overwrite with the author
    # reading when the authority table provides one.
    prim = by_field.get("author") or by_field.get("editor") or []
    yomis = [n["yomi"] for n in prim if n.get("yomi")]
    if yomis:
        new_yomi = " and ".join(yomis)
        if entry.get("yomi", "") != new_yomi:
            entry["yomi"] = new_yomi
            changed.append("yomi")
    return changed, mismatched


_CONCAT = re.compile(r"[ 　,]")


def load_manual(path: Path) -> dict[str, tuple[str, str]]:
    """{concatenated_name: (split, provenance)} from the manual split table."""
    table: dict[str, tuple[str, str]] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        r = json.loads(line)
        table[r["name"]] = (r["split"], r.get("provenance", "manual"))
    return table


def apply_manual_names(entry: dict, manual: dict[str, tuple[str, str]]) -> list[str]:
    """Apply the name→split table (keyed by concatenated form). Returns the list
    of provenance labels applied. Names already comma-split are left as-is."""
    applied: list[str] = []
    for fld in NAME_FIELDS:
        v = entry.get(fld, "")
        if not v.strip():
            continue
        names = re.split(r"\s+and\s+", v.strip())
        out, changed = [], False
        for nm in names:
            if "," in nm:
                out.append(nm)
                continue
            concat = _CONCAT.sub("", nm.strip())
            if concat in manual:
                out.append(manual[concat][0])
                applied.append(manual[concat][1])
                changed = True
            else:
                out.append(nm)
        if changed:
            entry[fld] = " and ".join(out)
    return applied


def fix_misc_url(entry: dict) -> bool:
    """De-duplicate URL in @misc: url field wins, howpublished loses the URL."""
    if entry.get("ENTRYTYPE", "").lower() != "misc":
        return False
    hp = entry.get("howpublished", "")
    if not hp:
        return False
    m = _URL_BRACE.search(hp)
    hp_url = m.group(1) if m else (_URL_RAW.search(hp).group(0) if _URL_RAW.search(hp) else None)
    if hp_url is None:
        return False
    changed = False
    if not entry.get("url", "").strip():
        entry["url"] = hp_url
        changed = True
    remainder = _URL_RAW.sub("", _URL_BRACE.sub("", hp)).strip(" ,;　:：\t").strip()
    if remainder:
        if remainder != hp:
            entry["howpublished"] = remainder
            changed = True
    else:
        entry.pop("howpublished", None)
        changed = True
    return changed


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--in", dest="src", type=Path, default=REPO / "dataset" / "ja_bib_full.bib")
    ap.add_argument("--out", dest="dst", type=Path, default=REPO / "dataset" / "ja_bib_derived.bib")
    ap.add_argument("--names-table", type=Path, default=None,
                    help="enrichment JSONL (provisional_key キー; author_split/yomi/typ 典拠)")
    ap.add_argument("--key-map", type=Path, default=REPO / "key_map.csv",
                    help="final-key ↔ provisional_key 対応表（merge_assign_keys.py 出力）")
    ap.add_argument("--manual-table", type=Path, default=None,
                    help="手動/Web 確定の姓名分割テーブル JSONL（name→split・provenance）")
    args = ap.parse_args()

    if not args.src.exists():
        print(f"input not found: {args.src}", file=sys.stderr)
        return 1

    enrich: dict[str, dict] = {}
    if args.names_table:
        if not args.key_map.exists():
            print(f"--names-table given but key map not found: {args.key_map}", file=sys.stderr)
            return 1
        enrich = load_enrichment(args.names_table, args.key_map)
    manual = load_manual(args.manual_table) if args.manual_table else {}

    entries = biblib.load_bib(args.src)
    n_enriched = n_yomi = n_names = n_misc = n_ambig = n_mism = 0
    n_manual: dict[str, int] = {}
    for e in entries:
        key = e.get("ID", "?")
        if key in enrich:
            changed, mism = apply_enrichment(e, enrich[key])
            if changed:
                n_enriched += 1
                n_yomi += "yomi" in changed
            for f in mism:
                n_mism += 1
                print(f"[enrich-mismatch] {key}.{f}: record author differs from table original; skipped",
                      file=sys.stderr)
        for prov in apply_manual_names(e, manual):
            n_manual[prov] = n_manual.get(prov, 0) + 1
        for fld in NAME_FIELDS:
            if fld in e and e[fld].strip():
                new, changes, ambiguous = biblib.convert_author_field(e[fld])
                if changes:
                    e[fld] = new
                    n_names += len(changes)
                for nm in ambiguous:
                    n_ambig += 1
                    print(f"[ambiguous] {key}.{fld}: left as-is (Japanese, >1 space): {nm!r}",
                          file=sys.stderr)
        if fix_misc_url(e):
            n_misc += 1

    args.dst.parent.mkdir(parents=True, exist_ok=True)
    biblib.write_bib(entries, args.dst)
    args.dst.write_text(HEADER + args.dst.read_text(encoding="utf-8"), encoding="utf-8")

    print(f"wrote {args.dst}  ({len(entries)} entries; enriched={n_enriched} "
          f"(yomi added={n_yomi}, mismatch={n_mism}); manual splits={dict(n_manual)}; "
          f"author names converted={n_names}, @misc url fixed={n_misc}, ambiguous={n_ambig})",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
